-- V10: contas de usuario e dono da ficha (incremento 2.2, spec do login §2).
-- Mesmo padrao das migracoes anteriores: identity, timestamptz e CHECKs como rede de seguranca.
-- A V1 a V9 nao sao editadas (o Flyway compara o checksum de migracoes ja aplicadas).

-- 1) Usuario. senha_hash nulo = a conta nao entra com senha (o usuario "legado" e as contas do Google do 2.5).
--    O CHECK garante e-mail em minusculas mesmo se alguem gravar por fora da API.
create table usuario (
    id         bigint        generated by default as identity primary key,
    email      varchar(255)  not null unique check (email = lower(email)),
    nome       varchar(100)  not null,
    senha_hash varchar(100),
    criado_em  timestamptz   not null default now()
);

-- 2) Refresh token. So o SHA-256 (hexadecimal, 64 caracteres) do token e guardado. "familia" identifica cada login:
--    revogar a cadeia inteira (reuso detectado) e um UPDATE ... WHERE familia = ?. substituido_por liga ao token filho.
create table refresh_token (
    id              bigint       generated by default as identity primary key,
    usuario_id      bigint       not null references usuario (id),
    familia         uuid         not null,
    hash            varchar(64)  not null unique,
    criado_em       timestamptz  not null,
    expira_em       timestamptz  not null,
    revogado_em     timestamptz,
    substituido_por bigint       references refresh_token (id)
);
create index ix_refresh_token_familia on refresh_token (familia);
create index ix_refresh_token_usuario on refresh_token (usuario_id);

-- 3) Usuario "legado": dono provisorio das fichas que ja existiam. O dominio .invalid e reservado (RFC 2606) e nunca
--    recebe e-mail; com senha_hash nulo ele nao entra de jeito nenhum.
insert into usuario (email, nome, senha_hash) values ('legado@fichas-rpg.invalid', 'Fichas antigas', null);

-- 4) dono_id entra aceitando nulo, as fichas existentes passam para o legado, e so entao vira obrigatorio.
alter table ficha add column dono_id bigint references usuario (id);
update ficha set dono_id = (select id from usuario where email = 'legado@fichas-rpg.invalid');
alter table ficha alter column dono_id set not null;
create index ix_ficha_dono on ficha (dono_id);
