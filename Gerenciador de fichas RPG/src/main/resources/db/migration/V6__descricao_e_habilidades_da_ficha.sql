-- V6: descricao e habilidades da ficha (incremento 2.1g, spec das abas §3.1). Vale para os dois sistemas.
-- A descricao (aparencia, historia e anotacoes) fica em colunas novas da tabela comum ficha: sao texto livre,
-- opcional, e todo sistema tem. As habilidades sao uma lista, entao ganham uma tabela propria (ficha_habilidade).
-- O Flyway roda este arquivo numa transacao so (DDL transacional do PostgreSQL).
-- A V1 a V5 nao sao editadas (o Flyway compara o checksum de migracoes ja aplicadas).

-- 1) Descricao: ate 4000 caracteres cada, nula quando vazia (a API converte texto vazio em null).
alter table ficha
    add column aparencia  varchar(4000),
    add column historia   varchar(4000),
    add column anotacoes  varchar(4000);

-- 2) Habilidades: uma linha por habilidade. Apagar a ficha apaga as habilidades (on delete cascade).
--    A ordem da lista e a de criacao (id). A check lista os tipos dos dois sistemas; qual tipo vale em qual
--    sistema e regra da API (TipoHabilidade.permitidoEm), porque a ficha_habilidade nao sabe o sistema da ficha.
create table ficha_habilidade (
    id        bigint        generated by default as identity primary key,
    ficha_id  bigint        not null references ficha (id) on delete cascade,
    nome      varchar(255)  not null,
    tipo      varchar(15)   not null check (tipo in ('CLASSE', 'TRILHA', 'ORIGEM', 'PARANORMAL', 'SUBCLASSE', 'ESPECIE', 'ANTECEDENTE', 'TALENTO', 'OUTRA')),
    descricao varchar(4000)
);

-- 3) Listar as habilidades de uma ficha e o cascade da exclusao usam ficha_id.
create index ix_ficha_habilidade_ficha on ficha_habilidade (ficha_id);
