-- V8: magias e espacos de magia (D&D) e rituais (Ordem Paranormal), incremento 2.1j (spec das abas, 3.4).
-- Segue o desenho da V7: uma tabela de lista por sistema, ligada so do lado da lista, para a listagem de
-- fichas continuar em 1 consulta (ADR 0018). As regras de valor (faixas, usados <= total) ficam tambem no
-- banco, como rede de seguranca: a API ja valida antes.
-- A chave primaria das tabelas de sistema se chama ficha_id (V4 e V5), e e para ela que as FKs apontam.
-- O Flyway roda este arquivo numa transacao so (DDL transacional do PostgreSQL).
-- A V1 a V7 nao sao editadas (o Flyway compara o checksum de migracoes ja aplicadas).

-- 1) Atributo de conjuracao da ficha de D&D: so atributos mentais; nulo = a ficha nao conjura.
--    As fichas que ja existem ficam sem atributo.
alter table ficha_dnd
    add column atributo_conjuracao varchar(3) check (atributo_conjuracao in ('INT', 'SAB', 'CAR'));

-- 2) Magias de D&D: nivel 0 (truque) a 9. Os campos de texto curtos sao opcionais; os tres marcadores
--    comecam em falso. Apagar a ficha apaga as magias (on delete cascade). A ordem da lista e nivel e id.
create table ficha_dnd_magia (
    id           bigint        generated by default as identity primary key,
    ficha_id     bigint        not null references ficha_dnd (ficha_id) on delete cascade,
    nome         varchar(255)  not null,
    nivel        integer       not null check (nivel between 0 and 9),
    escola       varchar(255),
    tempo        varchar(255),
    alcance      varchar(255),
    componentes  varchar(255),
    duracao      varchar(255),
    concentracao boolean       not null default false,
    ritual       boolean       not null default false,
    preparada    boolean       not null default false,
    descricao    varchar(4000)
);

-- 3) Espacos de magia: uma linha por nivel (1 a 9) que a ficha ja configurou; nivel sem linha vale 0 de 0.
--    A chave primaria (ficha_id, nivel) ja serve de indice por ficha.
create table ficha_dnd_espaco (
    ficha_id bigint  not null references ficha_dnd (ficha_id) on delete cascade,
    nivel    integer not null check (nivel between 1 and 9),
    total    integer not null check (total >= 0),
    usados   integer not null check (usados >= 0),
    primary key (ficha_id, nivel),
    check (usados <= total)
);

-- 4) Rituais de Ordem Paranormal: circulo 1 a 4 e um dos cinco elementos. A ordem da lista e circulo e id.
create table ficha_ordem_ritual (
    id          bigint        generated by default as identity primary key,
    ficha_id    bigint        not null references ficha_ordem (ficha_id) on delete cascade,
    nome        varchar(255)  not null,
    circulo     integer       not null check (circulo between 1 and 4),
    elemento    varchar(20)   not null check (elemento in ('SANGUE', 'MORTE', 'CONHECIMENTO', 'ENERGIA', 'MEDO')),
    execucao    varchar(255),
    alcance     varchar(255),
    alvo        varchar(255),
    duracao     varchar(255),
    resistencia varchar(255),
    descricao   varchar(4000)
);

-- 5) Listar as magias e os rituais de uma ficha e o cascade da exclusao usam ficha_id.
create index ix_ficha_dnd_magia_ficha on ficha_dnd_magia (ficha_id);
create index ix_ficha_ordem_ritual_ficha on ficha_ordem_ritual (ficha_id);
