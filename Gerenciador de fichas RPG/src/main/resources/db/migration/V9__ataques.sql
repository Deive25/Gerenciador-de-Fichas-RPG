-- V9: ataques da ficha (incremento 2.1i, spec das abas §3.3). Uma tabela por sistema, como a V7 e a V8: a
-- ligacao e so do lado do ataque, entao a listagem de fichas continua em 1 consulta (ADR 0018).
-- Os CHECKs repetem as regras da API (faixas, pericias e atributos aceitos) como rede de seguranca. O texto do
-- dano e a notacao de dados ja validada e canonica (ex.: 1d8+3): no maximo 8 termos de 6 caracteres cabem em 60.
-- A chave primaria das tabelas de sistema se chama ficha_id (V4 e V5), e e para ela que as FKs apontam.
-- O Flyway roda este arquivo numa transacao so (DDL transacional do PostgreSQL).
-- A V1 a V8 nao sao editadas (o Flyway compara o checksum de migracoes ja aplicadas).

-- 1) Ataques de Ordem Paranormal: a pericia do teste (Luta ou Pontaria), o bonus fixo, a margem de ameaca
--    (de 2 a 20, padrao 20) e o multiplicador do critico (de 2 a 5, padrao 2). A ordem da lista e a de criacao (id).
--    Apagar a ficha apaga os ataques (on delete cascade).
create table ficha_ordem_ataque (
    id            bigint        generated by default as identity primary key,
    ficha_id      bigint        not null references ficha_ordem (ficha_id) on delete cascade,
    nome          varchar(255)  not null,
    pericia       varchar(20)   not null check (pericia in ('LUTA', 'PONTARIA')),
    bonus         integer       not null default 0 check (bonus between -99 and 99),
    dano          varchar(60)   not null,
    tipo_dano     varchar(255),
    alcance       varchar(255),
    margem        integer       not null default 20 check (margem between 2 and 20),
    multiplicador integer       not null default 2 check (multiplicador between 2 and 5)
);

-- 2) Ataques de D&D: o atributo do ataque (os seis), se a ficha soma a proficiencia e o bonus fixo.
create table ficha_dnd_ataque (
    id          bigint        generated by default as identity primary key,
    ficha_id    bigint        not null references ficha_dnd (ficha_id) on delete cascade,
    nome        varchar(255)  not null,
    atributo    varchar(3)    not null check (atributo in ('FOR', 'DES', 'CON', 'INT', 'SAB', 'CAR')),
    proficiente boolean       not null default false,
    bonus       integer       not null default 0 check (bonus between -99 and 99),
    dano        varchar(60)   not null,
    tipo_dano   varchar(255),
    alcance     varchar(255)
);

-- 3) Listar os ataques de uma ficha e o cascade da exclusao usam ficha_id.
create index ix_ficha_ordem_ataque_ficha on ficha_ordem_ataque (ficha_id);
create index ix_ficha_dnd_ataque_ficha on ficha_dnd_ataque (ficha_id);
