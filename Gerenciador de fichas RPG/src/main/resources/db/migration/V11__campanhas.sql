-- V11: campanhas, participacoes (papel Mestre/Jogador) e versao da ficha (incremento 2.3, spec das campanhas §3).
-- A V1 a V10 nao sao editadas (o Flyway compara o checksum de migracoes ja aplicadas).

create table campanha (
    id             bigint        generated by default as identity primary key,
    nome           varchar(100)  not null,
    descricao      varchar(1000),
    codigo_convite varchar(12)   not null unique,
    convite_ativo  boolean       not null default true,
    criado_em      timestamptz   not null default now()
);

create table participacao (
    campanha_id bigint       not null references campanha (id) on delete cascade,
    usuario_id  bigint       not null references usuario (id),
    papel       varchar(10)  not null check (papel in ('MESTRE', 'JOGADOR')),
    entrou_em   timestamptz  not null default now(),
    primary key (campanha_id, usuario_id)
);
create unique index ux_participacao_um_mestre on participacao (campanha_id) where papel = 'MESTRE';
create index ix_participacao_usuario on participacao (usuario_id);

alter table ficha add column campanha_id bigint;
alter table ficha add constraint fk_ficha_participacao
    foreign key (campanha_id, dono_id) references participacao (campanha_id, usuario_id)
    on delete set null (campanha_id);
create index ix_ficha_campanha on ficha (campanha_id);

alter table ficha add column versao bigint not null default 0;
