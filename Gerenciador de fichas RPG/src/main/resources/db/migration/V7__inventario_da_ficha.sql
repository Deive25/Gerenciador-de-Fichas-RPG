-- V7: inventario da ficha (incremento 2.1h, spec das abas §3.2). Itens nos dois sistemas e moedas em D&D.
-- Cada sistema tem os seus campos, entao cada um ganha a sua tabela de itens: ficha_ordem_item (categoria e
-- espacos) e ficha_dnd_item (peso e equipado). As moedas sao cinco numeros por ficha, entao viram colunas
-- da ficha_dnd. As fichas nao ganham colecao de itens: a listagem continua em 1 consulta (ADR 0018).
-- A chave primaria das tabelas de sistema se chama ficha_id (V4 e V5), e e para ela que a FK dos itens aponta.
-- O Flyway roda este arquivo numa transacao so (DDL transacional do PostgreSQL).
-- A V1 a V6 nao sao editadas (o Flyway compara o checksum de migracoes ja aplicadas).

-- 1) Itens de Ordem Paranormal: categoria de 0 a 4 (mostrada como 0, I, II, III, IV), espacos e quantidade.
--    Apagar a ficha apaga os itens (on delete cascade). A ordem da lista e a de criacao (id).
create table ficha_ordem_item (
    id         bigint        generated by default as identity primary key,
    ficha_id   bigint        not null references ficha_ordem (ficha_id) on delete cascade,
    nome       varchar(255)  not null,
    categoria  integer       not null check (categoria between 0 and 4),
    espacos    integer       not null check (espacos >= 0),
    quantidade integer       not null check (quantidade >= 1),
    descricao  varchar(4000)
);

-- 2) Itens de D&D: peso em kg por unidade (ate 99999,99), quantidade e se esta equipado.
create table ficha_dnd_item (
    id         bigint        generated by default as identity primary key,
    ficha_id   bigint        not null references ficha_dnd (ficha_id) on delete cascade,
    nome       varchar(255)  not null,
    quantidade integer       not null check (quantidade >= 1),
    peso       numeric(7,2)  not null check (peso >= 0),
    equipado   boolean       not null default false,
    descricao  varchar(4000)
);

-- 3) Listar os itens de uma ficha e o cascade da exclusao usam ficha_id.
create index ix_ficha_ordem_item_ficha on ficha_ordem_item (ficha_id);
create index ix_ficha_dnd_item_ficha on ficha_dnd_item (ficha_id);

-- 4) Moedas de D&D: cobre, prata, electro, ouro e platina. As fichas que ja existem ficam com 0.
alter table ficha_dnd
    add column pc integer not null default 0 check (pc >= 0),
    add column pp integer not null default 0 check (pp >= 0),
    add column pe integer not null default 0 check (pe >= 0),
    add column po integer not null default 0 check (po >= 0),
    add column pl integer not null default 0 check (pl >= 0);
